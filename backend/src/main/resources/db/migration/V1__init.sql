-- TokenFest initial schema. Must run on both PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE admin_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- An upstream LLM account (OpenAI, Anthropic, DeepSeek, ...)
CREATE TABLE providers (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL UNIQUE,
    provider_type     VARCHAR(20)  NOT NULL,              -- OPENAI or ANTHROPIC (API format)
    base_url          VARCHAR(500) NOT NULL,
    api_key_encrypted VARCHAR(1000) NOT NULL,             -- AES-GCM, never returned by the API
    priority          INT          NOT NULL DEFAULT 100,  -- lower number is tried first
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE provider_models (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id  BIGINT        NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    model_name   VARCHAR(200)  NOT NULL,
    input_price  NUMERIC(12, 6) NOT NULL DEFAULT 0,  -- USD per 1M input tokens
    output_price NUMERIC(12, 6) NOT NULL DEFAULT 0,  -- USD per 1M output tokens
    CONSTRAINT uq_provider_models UNIQUE (provider_id, model_name)
);

-- A TokenFest key given to one team member
CREATE TABLE api_keys (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    key_hash              VARCHAR(64)  NOT NULL UNIQUE,  -- SHA-256 (hex) of the full key
    key_prefix            VARCHAR(20)  NOT NULL,         -- first characters, shown in the dashboard
    monthly_budget        NUMERIC(12, 4),                -- USD, NULL = no limit
    rate_limit_per_minute INT,                           -- NULL = no limit
    enabled               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at          TIMESTAMP WITH TIME ZONE
);

-- Providers a key may use. No rows = all providers.
CREATE TABLE api_key_providers (
    api_key_id  BIGINT NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    provider_id BIGINT NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    PRIMARY KEY (api_key_id, provider_id)
);

CREATE TABLE request_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_key_id    BIGINT       NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    provider_id   BIGINT       REFERENCES providers (id) ON DELETE SET NULL,
    api_format    VARCHAR(20)  NOT NULL,  -- endpoint the client called: OPENAI or ANTHROPIC
    model         VARCHAR(200),
    status_code   INT          NOT NULL,
    streamed      BOOLEAN      NOT NULL DEFAULT FALSE,
    input_tokens  INT          NOT NULL DEFAULT 0,
    output_tokens INT          NOT NULL DEFAULT 0,
    cost          NUMERIC(14, 6) NOT NULL DEFAULT 0,
    latency_ms    INT          NOT NULL DEFAULT 0,
    attempts      INT          NOT NULL DEFAULT 1,
    error_message VARCHAR(1000),
    request_body  TEXT,
    response_body TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_request_logs_created ON request_logs (created_at);
CREATE INDEX idx_request_logs_key_created ON request_logs (api_key_id, created_at);

-- Totals per day, key, provider and model. Used for charts and budget checks.
CREATE TABLE usage_daily (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_date    DATE         NOT NULL,
    api_key_id    BIGINT       NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    provider_id   BIGINT       REFERENCES providers (id) ON DELETE SET NULL,
    model         VARCHAR(200) NOT NULL,
    request_count INT          NOT NULL DEFAULT 0,
    input_tokens  BIGINT       NOT NULL DEFAULT 0,
    output_tokens BIGINT       NOT NULL DEFAULT 0,
    cost          NUMERIC(14, 6) NOT NULL DEFAULT 0,
    CONSTRAINT uq_usage_daily UNIQUE (usage_date, api_key_id, provider_id, model)
);
CREATE INDEX idx_usage_daily_key_date ON usage_daily (api_key_id, usage_date);

-- One row per budget threshold reached per key per month, so alerts are never sent twice
CREATE TABLE alert_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_key_id        BIGINT        NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    budget_month      VARCHAR(7)    NOT NULL,  -- e.g. 2026-10
    threshold_percent INT           NOT NULL,
    spent             NUMERIC(14, 6) NOT NULL,
    budget            NUMERIC(12, 4) NOT NULL,
    delivered         BOOLEAN       NOT NULL,
    error_message     VARCHAR(1000),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_alert_events UNIQUE (api_key_id, budget_month, threshold_percent)
);

-- Settings that the admin can change from the dashboard (alert thresholds, webhook URL, ...)
CREATE TABLE app_settings (
    setting_key   VARCHAR(100)  PRIMARY KEY,
    setting_value VARCHAR(2000) NOT NULL
);
